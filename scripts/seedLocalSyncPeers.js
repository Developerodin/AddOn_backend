/**
 * Local Mac sync test only (addon = cloud stand-in on :8000, addon2 = factory stand-in on Docker :8001).
 *
 * - addon  : SyncCredential siteId `factory-mac`  → key the Docker worker presents to :8000.
 *            Written to factory/.env.local-test (SYNC_PEER_KEY_ID / SYNC_PEER_CREDENTIAL).
 * - addon2 : SyncCredential siteId `cloud-mac`    → key the dev API presents to :8001.
 *            Written into AddOn_backend/.env together with the dev SYNC_* flags.
 *
 * - addon  : SyncCredential siteId `cloud-mac` (label local-mac-cloud-probe) → used only by
 *            scripts/syncEndToEndTest.js to post the cloud side of a concurrent edit to :8000.
 *            Written to factory/.env.local-probe (SYNC_PROBE_CLOUD_KEY_ID / SYNC_PROBE_CLOUD_CREDENTIAL).
 *            Kept out of AddOn_backend/ so it is not in the Docker build context or the container env.
 *
 * Earlier rows created by this script (same label) are revoked first, so re-running rotates the keys.
 * `--probe-only` rotates just the cloud-mac probe key on addon; the factory and dev peer keys are untouched.
 * Refuses to run unless MONGODB_URL is a loopback host with database `addon`.
 * Prints only file-write confirmations; never prints secrets or connection strings.
 *
 * Run from AddOn_backend/:  NODE_ENV=development node scripts/seedLocalSyncPeers.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import mongoose from 'mongoose';
import config from '../src/config/config.js';
import { connectMongooseForScript } from './lib/mongoScriptConnect.js';
import SyncCredential from '../src/models/sync/syncCredential.model.js';
import { createSiteCredential } from '../src/services/sync/syncCredential.service.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const backendDir = path.resolve(here, '..');
const factoryEnvPath = path.resolve(backendDir, '../factory/.env.local-test');
const probeEnvPath = path.resolve(backendDir, '../factory/.env.local-probe');
const devEnvPath = path.resolve(backendDir, '.env');
const LABEL = 'local-mac-sync-test';
const PROBE_LABEL = 'local-mac-cloud-probe';

/** @param {string} url @param {string} db */
const withDb = (url, db) => {
  const u = new URL(url);
  u.pathname = `/${db}`;
  return u.toString();
};

const assertLocalAddon = (url) => {
  const u = new URL(url);
  const host = u.hostname;
  const db = u.pathname.replace(/^\//, '');
  if (!['127.0.0.1', 'localhost', '::1', '[::1]'].includes(host) || db !== 'addon') {
    throw new Error('Refusing to run: MONGODB_URL must be a loopback host with database "addon".');
  }
};

/** Revoke previous rows from this script for siteId, then create a fresh credential on the current connection. */
const rotate = async (siteId, label = LABEL) => {
  await SyncCredential.updateMany({ siteId, label, revoked: false }, { $set: { revoked: true } });
  return createSiteCredential({ siteId, label });
};

/** cloud-mac key on addon (:8000) for the e2e probe's concurrent-edit cases. Caller holds the addon connection. */
const writeProbeKey = async () => {
  const probeKey = await rotate('cloud-mac', PROBE_LABEL);
  fs.writeFileSync(
    probeEnvPath,
    [
      '# Local Mac sync probe only. cloud-mac key on database addon (:8000). Generated by seedLocalSyncPeers.js. Do not commit.',
      `SYNC_PROBE_CLOUD_KEY_ID=${probeKey.keyId}`,
      `SYNC_PROBE_CLOUD_CREDENTIAL=${probeKey.secret}`,
      '',
    ].join('\n'),
    { mode: 0o600 }
  );
  console.log('wrote factory/.env.local-probe');
};

const connectTo = async (url) => {
  await connectMongooseForScript({ mongoose: { ...config.mongoose, url } });
};

/**
 * Set or replace KEY=value lines; append missing keys. Other lines are untouched.
 * @param {string} file @param {Record<string,string>} values
 */
const upsertEnv = (file, values) => {
  const original = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const lines = original.length ? original.split('\n') : [];
  const seen = new Set();
  const out = lines.map((line) => {
    const m = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/);
    if (m && Object.prototype.hasOwnProperty.call(values, m[1])) {
      seen.add(m[1]);
      return `${m[1]}=${values[m[1]]}`;
    }
    return line;
  });
  const missing = Object.keys(values).filter((k) => !seen.has(k));
  if (missing.length) {
    if (out.length && out[out.length - 1] !== '') out.push('');
    missing.forEach((k) => out.push(`${k}=${values[k]}`));
    out.push('');
  }
  fs.writeFileSync(file, out.join('\n'), { mode: 0o600 });
};

const main = async () => {
  const baseUrl = config.mongoose.url;
  assertLocalAddon(baseUrl);

  await connectTo(baseUrl);
  if (process.argv.includes('--probe-only')) {
    await writeProbeKey();
    await mongoose.disconnect();
    return;
  }
  const factoryKey = await rotate('factory-mac');
  await writeProbeKey();
  await mongoose.disconnect();

  await connectTo(withDb(baseUrl, 'addon2'));
  const cloudKey = await rotate('cloud-mac');
  await mongoose.disconnect();

  fs.writeFileSync(
    factoryEnvPath,
    [
      '# Local Mac sync test only. Generated by AddOn_backend/scripts/seedLocalSyncPeers.js. Do not commit.',
      `SYNC_PEER_KEY_ID=${factoryKey.keyId}`,
      `SYNC_PEER_CREDENTIAL=${factoryKey.secret}`,
      '',
    ].join('\n'),
    { mode: 0o600 }
  );
  console.log('wrote factory/.env.local-test');

  upsertEnv(devEnvPath, {
    SYNC_ENABLED: 'true',
    SYNC_SHADOW_VENDOR_TRANSFER: 'true',
    SYNC_WORKER_ENABLED: 'true',
    SYNC_SITE_ID: 'cloud-mac',
    SYNC_PEER_BASE_URL: 'http://127.0.0.1:8001/v1/sync',
    SYNC_PEER_KEY_ID: cloudKey.keyId,
    SYNC_PEER_CREDENTIAL: cloudKey.secret,
  });
  console.log('updated dev sync env');
};

main().catch(async (err) => {
  console.error(err && err.message ? err.message : 'seedLocalSyncPeers failed');
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
